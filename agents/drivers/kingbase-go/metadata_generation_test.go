func TestInformationSchemaGeneratedExpressionFunctionFallbackIsCached(t *testing.T) {
	state := &metadataDriverState{query: func(query string) (driver.Rows, error) {
		if strings.Contains(query, "sys_get_expr(") {
			return nil, &gokb.Error{Code: "42883", Message: "function sys_get_expr(pg_node_tree, oid) does not exist"}
		}
		if !strings.Contains(query, "pg_get_expr(ad.adbin, ad.adrelid)") {
			return nil, errors.New("missing compatible generation expression function")
		}
		return generationMetadataRows(query, "", "s", "quantity * price"), nil
	}}
	srv := newServer()
	srv.db = openMetadataDB(t, state)
	for call := 0; call < 2; call++ {
		columns, err := srv.informationSchemaColumns("public", "orders", nil)
		if err != nil || len(columns) != 1 || columns[0].Extra == nil || *columns[0].Extra != "GENERATED ALWAYS AS (quantity * price) STORED" || columns[0].ColumnDefault != nil {
			t.Fatalf("generated expression lost in function fallback: %#v (%v)", columns, err)
		}
	}
	if queries := state.snapshotQueries(); len(queries) != 3 || !strings.Contains(queries[0], "sys_get_expr(") || strings.Contains(queries[2], "sys_get_expr(") {
		t.Fatalf("function fallback must be cached: %v", queries)
	}
}

func TestGenerationMetadataErrorsDoNotDisableCapabilities(t *testing.T) {
	for _, mysql := range []bool{false, true} {
		for _, failure := range []error{
			&gokb.Error{Code: "42501", Message: "permission denied for column attgenerated"},
			&gokb.Error{Code: "42703", Message: "column a.other_column does not exist"},
			errors.New("metadata connection reset"),
		} {
			t.Run(fmt.Sprintf("mysql=%v/%s", mysql, failure), func(t *testing.T) {
				state := &metadataDriverState{query: func(string) (driver.Rows, error) { return nil, failure }}
				srv := newServer()
				srv.db = openMetadataDB(t, state)
				var err error
				if mysql {
					_, err = srv.informationSchemaColumns("public", "orders", nil)
				} else {
					_, err = srv.queryCatalogColumns("public", "orders", "sys_catalog", "sys", "sys_get_expr")
				}
				if !errors.Is(err, failure) || len(state.snapshotQueries()) != 1 || srv.catalogIdentityUnsupported || srv.catalogGeneratedUnsupported {
					t.Fatalf("unrelated failure must propagate without downgrading metadata: %v", err)
				}
			})
		}
	}
}

func TestDisconnectResetsGeneratedColumnCapability(t *testing.T) {
	srv := newServer()
	srv.catalogGeneratedUnsupported = true
	if err := srv.disconnect(); err != nil {
		t.Fatal(err)
	}
	_, projection := srv.catalogColumnGenerationExpressions()
	if srv.catalogGeneratedUnsupported || projection != "a.attgenerated" {
		t.Fatal("new connections must reprobe generated-column support")
	}
}
