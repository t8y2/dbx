import type { DatabaseType } from "@/types/database";
import { sqlSemanticDialectFor } from "@/lib/sql/semantic/dialect";
import { tokenIsIdentifier, tokenizeSqlSemantic, unquoteSqlSemanticIdentifier } from "@/lib/sql/semantic/tokens";

/** Read conditions from the generated table SELECT, including inside ROWNUM
 * wrappers. Never reconstruct an executed query from the editor's draft. */
export function dataGridExecutedQueryConditions(sql: string, tableName: string, databaseType?: DatabaseType): { whereInput?: string; orderBy?: string } | null {
  const tokens = tokenizeSqlSemantic(sql, sqlSemanticDialectFor({ databaseType }).id).filter((token) => token.kind !== "comment");
  // The shallowest matching physical FROM owns the executed table conditions;
  // a nested predicate can query the same table without owning this page.
  let fromIndex = -1;
  for (let index = 0; index < tokens.length; index++) {
    const item = tokens[index]!;
    if (item.kind !== "word" || item.normalized !== "from") continue;
    let nameIndex = index + 1;
    if (!tokenIsIdentifier(tokens[nameIndex])) continue;
    while (tokens[nameIndex + 1]?.text === "." && tokenIsIdentifier(tokens[nameIndex + 2])) nameIndex += 2;
    if (unquoteSqlSemanticIdentifier(tokens[nameIndex]!).toLowerCase() !== tableName.toLowerCase()) continue;
    if (fromIndex < 0 || item.depth < tokens[fromIndex]!.depth) fromIndex = index;
  }
  if (fromIndex < 0) return null;
  const depth = tokens[fromIndex]!.depth;
  let selectIndex = fromIndex - 1;
  while (selectIndex >= 0 && !(tokens[selectIndex]!.depth === depth && tokens[selectIndex]!.normalized === "select")) selectIndex--;
  // A ROW_NUMBER window carries its ordering inside the projection, not the
  // table's ORDER BY clause. Keep the existing SQL for that unsupported shape.
  if (selectIndex < 0 || tokens.slice(selectIndex, fromIndex).some((token, index) => token.kind === "word" && token.normalized === "row_number" && tokens[selectIndex + index + 1]?.text === "(")) return null;
  let whereStart: number | undefined;
  let whereEnd: number | undefined;
  let orderStart: number | undefined;
  let orderEnd: number | undefined;
  let end = sql.length;
  const finishClauses = (position: number) => {
    if (whereStart !== undefined && whereEnd === undefined) whereEnd = position;
    if (orderStart !== undefined && orderEnd === undefined) orderEnd = position;
  };
  for (let index = fromIndex + 1; index < tokens.length; index++) {
    const item = tokens[index]!;
    if (item.depth < depth || (item.depth === depth && item.text === ";")) {
      end = item.span.start;
      break;
    }
    if (item.depth !== depth || item.kind !== "word") continue;
    // These are not shapes generated by the table browser. Decline rather than
    // dropping an aggregation/set operation or silently changing its meaning.
    if (["union", "intersect", "except", "minus", "group", "having", "join"].includes(item.normalized)) return null;
    if (item.normalized === "where") whereStart = item.span.end;
    else if (item.normalized === "order" && tokens[index + 1]?.normalized === "by") {
      finishClauses(item.span.start);
      orderStart = tokens[index + 1]!.span.end;
      index++;
    } else if (["limit", "offset", "fetch", "for"].includes(item.normalized)) finishClauses(item.span.start);
  }
  finishClauses(end);
  return {
    whereInput: whereStart === undefined ? undefined : sql.slice(whereStart, whereEnd).trim() || undefined,
    orderBy: orderStart === undefined ? undefined : sql.slice(orderStart, orderEnd).trim() || undefined,
  };
}
