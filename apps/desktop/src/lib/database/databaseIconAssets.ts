export function normalizeDatabaseIconType(type?: string): string {
  return (type || "").toLowerCase().replace(/[\s-]+/g, "_");
}

export function databaseIconAssetName(type?: string): string | undefined {
  const normalized = normalizeDatabaseIconType(type);
  return Object.prototype.hasOwnProperty.call(databaseIconAssets, normalized) ? databaseIconAssets[normalized] : undefined;
}

export function databaseIconAssetPath(type?: string): string | undefined {
  const name = databaseIconAssetName(type);
  return name ? `/icons/database/${name.includes(".") ? name : `${name}.svg`}` : undefined;
}
