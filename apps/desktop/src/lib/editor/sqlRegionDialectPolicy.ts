export interface SqlRegionDialectSpec extends SQLDialectSpec {
  regionDollarQuotes?: Exclude<SqlRegionDollarQuotes, "dialect">;
  regionTripleQuotes?: boolean;
  // Spark raw literals do not use backslashes even to protect the closing quote.
  regionRawStrings?: boolean;
  regionEscapeStrings?: boolean;
  regionIdentifierEscapes?: boolean;
  // SQLite/Access end at the first ], unlike SQL Server's escaped ]].
  regionDoubledBracketEscapes?: boolean;
  regionNestedBlockComments?: boolean;
  regionBlockComments?: boolean;
  regionDashComments?: boolean;
  regionClickHouseHashComments?: boolean;
  regionLineCommentContinuation?: boolean;
}

