use dbx_core::connection::AppState;
use dbx_core::database_export::{export_database_sql_core, DatabaseExportRequest};
use dbx_core::models::connection::{ConnectionConfig, DatabaseType};
use dbx_core::query::execute_sql_statement;
use dbx_core::sql::SqlFileRequest;
use dbx_core::sql_file_import::execute_sql_file_path;
use std::sync::Arc;
use tokio_util::sync::CancellationToken;

fn live_oracle_config(id: &str) -> ConnectionConfig {
    let host = std::env::var("DBX_LIVE_ORACLE_HOST").expect("DBX_LIVE_ORACLE_HOST");
    let port = std::env::var("DBX_LIVE_ORACLE_PORT").ok().and_then(|value| value.parse::<u16>().ok()).unwrap_or(1521);
    let service = std::env::var("DBX_LIVE_ORACLE_SERVICE").expect("DBX_LIVE_ORACLE_SERVICE");
    let username = std::env::var("DBX_LIVE_ORACLE_USER").expect("DBX_LIVE_ORACLE_USER");
    let password = std::env::var("DBX_LIVE_ORACLE_PASSWORD").expect("DBX_LIVE_ORACLE_PASSWORD");

    serde_json::from_value(serde_json::json!({
        "id": id,
        "name": id,
        "db_type": DatabaseType::Oracle,
        "host": host,
        "port": port,
        "username": username,
        "password": password,
        "database": service,
        "connect_timeout_secs": 10,
        "query_timeout_secs": 60,
        "idle_timeout_secs": 60,
        "keepalive_interval_secs": 0
    }))
    .expect("live Oracle config should deserialize")
}

fn first_cell(result: &dbx_core::types::QueryResult) -> String {
    match result.rows.first().and_then(|row| row.first()) {
        Some(serde_json::Value::String(value)) => value.clone(),
        Some(value) => value.to_string(),
        None => String::new(),
    }
}

/// The export covers the whole schema and the replay recreates every object in it,
/// so `DBX_LIVE_ORACLE_USER` must own an otherwise empty, disposable schema.
#[tokio::test]
#[ignore = "requires a disposable Oracle schema"]
async fn live_oracle_database_export_replays_trigger_sequences() {
    let suffix = uuid::Uuid::new_v4().simple().to_string()[..8].to_uppercase();
    let connection_id = format!("live-oracle-export-{suffix}");
    let dir = std::env::temp_dir().join(format!("dbx-live-oracle-export-{suffix}"));
    std::fs::create_dir_all(&dir).unwrap();
    let storage = dbx_core::persistence::test_storage::open(&dir.join("storage.db")).await.unwrap();
    let state = Arc::new(AppState::new(storage));
    state.configs.write().await.insert(connection_id.clone(), live_oracle_config(&connection_id));
    let service = std::env::var("DBX_LIVE_ORACLE_SERVICE").unwrap();
    let schema = std::env::var("DBX_LIVE_ORACLE_USER").unwrap().to_uppercase();

    let orders = format!("DBX_EXPORT_ORDERS_{suffix}");
    let sequence = format!("DBX_EXPORT_SEQ_{suffix}");
    let trigger = format!("DBX_EXPORT_TRG_{suffix}");
    let identity = format!("DBX_EXPORT_IDENT_{suffix}");
    let drop_all = [
        format!("DROP TABLE {orders} PURGE"),
        format!("DROP TABLE {identity} PURGE"),
        format!("DROP SEQUENCE {sequence}"),
    ];
    let run = |sql: String| {
        let state = state.clone();
        let connection_id = connection_id.clone();
        let service = service.clone();
        let schema = schema.clone();
        async move { execute_sql_statement(&state, &connection_id, &service, &sql, Some(&schema), None).await }
    };

    let file_path = dir.join("export.sql");
    let outcome = async {
        for sql in [
            format!("CREATE TABLE {orders} (ID NUMBER PRIMARY KEY, NOTE VARCHAR2(50))"),
            format!("CREATE SEQUENCE {sequence} START WITH 100 INCREMENT BY 5 NOCACHE"),
            format!(
                "CREATE OR REPLACE TRIGGER {trigger} BEFORE INSERT ON {orders} FOR EACH ROW\nBEGIN\n  IF :NEW.ID IS NULL THEN SELECT {sequence}.NEXTVAL INTO :NEW.ID FROM DUAL; END IF;\nEND;"
            ),
            format!("CREATE TABLE {identity} (ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)"),
            format!("INSERT INTO {orders} (NOTE) VALUES ('first')"),
            format!("INSERT INTO {orders} (NOTE) VALUES ('second')"),
        ] {
            run(sql).await?;
        }

        let request = DatabaseExportRequest {
            export_id: format!("live-oracle-export-{suffix}"),
            connection_id: connection_id.clone(),
            database: service.clone(),
            schema: schema.clone(),
            file_path: file_path.to_string_lossy().to_string(),
            selected_tables: Vec::new(),
            excluded_tables: Vec::new(),
            include_structure: true,
            include_data: true,
            include_objects: true,
            include_create_database: false,
            drop_table_if_exists: false,
            omit_auto_increment: false,
            preserve_original_language: false,
            fail_on_error: true,
            prevent_overwrite: false,
            output_compression: Default::default(),
            insert_dialect: Default::default(),
            insert_mode: Default::default(),
            snapshot_session_id: None,
            batch_size: 1000,
            split_max_mb: None,
        };
        export_database_sql_core(&state, &request, |_| {}).await?;
        let exported = std::fs::read_to_string(&file_path).map_err(|error| error.to_string())?;
        let sequence_position = exported
            .find(&format!("CREATE SEQUENCE  \"{schema}\".\"{sequence}\""))
            .ok_or_else(|| format!("CREATE SEQUENCE {sequence} missing from export:\n{exported}"))?;
        let trigger_position = exported
            .find(&format!("TRIGGER \"{schema}\".\"{trigger}\""))
            .ok_or_else(|| format!("trigger {trigger} missing from export:\n{exported}"))?;
        if sequence_position > trigger_position {
            return Err(format!("sequence {sequence} is exported after the trigger that uses it"));
        }
        if exported.contains("ISEQ$$_") {
            return Err("identity column sequence was exported as a standalone sequence".to_string());
        }

        for sql in drop_all.clone() {
            run(sql).await?;
        }
        let import_request = SqlFileRequest {
            txn_session_id: None,
            execution_id: format!("live-oracle-import-{suffix}"),
            connection_id: connection_id.clone(),
            database: service.clone(),
            schema: Some(schema.clone()),
            file_path: file_path.to_string_lossy().to_string(),
            continue_on_error: false,
            selected_tables: None,
            part_cooldown_ms: 0,
            skip_relational_constraints: false,
            failure_log_enabled: true,
            encoding: Default::default(),
        };
        execute_sql_file_path(
            &state,
            &import_request,
            &file_path,
            CancellationToken::new(),
            std::time::Instant::now(),
            |_| {},
        )
        .await?;

        let sequences = run(format!("SELECT COUNT(*) FROM USER_SEQUENCES WHERE SEQUENCE_NAME = '{sequence}'")).await?;
        if first_cell(&sequences) != "1" {
            return Err(format!("{sequence} was not recreated"));
        }
        let trigger_status = run(format!(
            "SELECT o.STATUS || '/' || t.STATUS FROM USER_OBJECTS o JOIN USER_TRIGGERS t ON t.TRIGGER_NAME = o.OBJECT_NAME \
             WHERE o.OBJECT_TYPE = 'TRIGGER' AND o.OBJECT_NAME = '{trigger}'"
        ))
        .await?;
        if first_cell(&trigger_status) != "VALID/ENABLED" {
            return Err(format!("{trigger} replayed as {}", first_cell(&trigger_status)));
        }
        run(format!("INSERT INTO {orders} (NOTE) VALUES ('after replay')")).await?;
        let next_id = run(format!("SELECT ID FROM {orders} WHERE NOTE = 'after replay'")).await?;
        if first_cell(&next_id) != "110" {
            return Err(format!("{sequence}.NEXTVAL resumed at {} instead of 110", first_cell(&next_id)));
        }
        Ok::<_, String>(())
    }
    .await;

    for sql in drop_all {
        let _ = run(sql).await;
    }
    drop(state);
    std::fs::remove_dir_all(&dir).unwrap();
    outcome.unwrap();
}
