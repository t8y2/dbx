/// Fixed catalog columns only; no identifier or accessor is supplied by a client.
#[derive(Clone, Copy)]
pub enum AnydataColumn {
    JobArgument,
    ProgramDefault,
}

pub fn anydata_projection(column: AnydataColumn) -> String {
    let column = column.sql();
    let type_name = format!("{column}.GetTypeName()");
    let null_access = ScalarType::ALL
        .into_iter()
        .map(|kind| {
            format!("WHEN '{}' THEN CASE WHEN {column}.{}() IS NULL THEN 1 ELSE 0 END", kind.token(), kind.access())
        })
        .collect::<Vec<_>>()
        .join(" ");
    let values = scalars::projection(column);
    format!(
        "CASE WHEN {column} IS NOT NULL THEN 1 ELSE 0 END AS DBX_ANYDATA_PRESENT, \
         CASE WHEN {column} IS NOT NULL THEN {type_name} END AS DBX_ANYDATA_TYPE, \
         DBX_AT.CODEC AS DBX_ANYDATA_CODEC, DBX_AT.TYPE_NAME AS DBX_ANYDATA_CONSTRUCTOR_TYPE, \
         CASE WHEN {column} IS NOT NULL THEN CASE DBX_AT.CODEC {null_access} ELSE NULL END END AS DBX_ANYDATA_IS_NULL, \
         CASE WHEN {column} IS NOT NULL THEN CASE DBX_AT.CODEC \
         WHEN 'number' THEN TO_CHAR({column}.AccessNumber(), 'TM9', 'NLS_NUMERIC_CHARACTERS=''.,''') \
         WHEN 'interval-ym' THEN TO_CHAR(EXTRACT(YEAR FROM {column}.AccessIntervalYM()) * 12 + EXTRACT(MONTH FROM {column}.AccessIntervalYM()), 'TM9', 'NLS_NUMERIC_CHARACTERS=''.,''') \
         WHEN 'interval-ds' THEN TO_CHAR((EXTRACT(DAY FROM {column}.AccessIntervalDS()) * 86400 + EXTRACT(HOUR FROM {column}.AccessIntervalDS()) * 3600 + EXTRACT(MINUTE FROM {column}.AccessIntervalDS()) * 60 + EXTRACT(SECOND FROM {column}.AccessIntervalDS())) * 1000000000, 'TM9', 'NLS_NUMERIC_CHARACTERS=''.,''') \
         WHEN 'urowid' THEN ROWIDTOCHAR({column}.AccessURowid()) ELSE NULL END END AS DBX_ANYDATA_TEXT, {values}"
    )
}

pub fn scalar_envelope(value: &Value) -> Result<ArgumentExpectation, &'static str> {
    let object = value.as_object().ok_or("native_job_argument_value_invalid")?;
    if object.len() != 3 || object.get("$dbx").and_then(Value::as_str) != Some("oracle-anydata-v1") {
        return Err("native_job_argument_value_invalid");
    }
    let kind = match (object.get("typeName"), object.get("scalarType")) {
        (Some(Value::String(name)), None) if name == "SYS.NUMBER" => ScalarType::Number,
        (None, Some(Value::String(token))) => {
            ScalarType::from_token(token).ok_or("native_job_argument_value_invalid")?
        }
        _ => return Err("native_job_argument_value_invalid"),
    };
    let value = object.get("value").ok_or("native_job_argument_value_invalid")?;
    let value = if object.contains_key("scalarType") && value.is_null() {
        None
    } else {
        Some(scalars::normalize(kind, value)?)
    };
    Ok(ArgumentExpectation { scalar_type: kind, value })
}

pub fn scalar_anydata_expression(value: &Value) -> Result<(String, ArgumentExpectation), &'static str> {
    let expected = scalar_envelope(value)?;
    Ok((scalars::expression(&expected)?, expected))
}

/// The optional setter is generated by the Job builder; a missing setter performs no writes.
pub fn scalar_value_block(value: &Value, setter: Option<&str>) -> Result<(String, ArgumentExpectation), &'static str> {
    let expected = scalar_envelope(value)?;
    let character = expected.value.is_some()
        && matches!(
            expected.scalar_type,
            ScalarType::Varchar2 | ScalarType::Char | ScalarType::Nvarchar2 | ScalarType::Nchar
        );
    let extra = if character { characters::declarations() } else { "" };
    let construction = if character {
        characters::construction(&expected)?
    } else {
        format!("l_anydata := {}; ", scalars::expression(&expected)?)
    };
    let validation = scalars::validation(&expected)?;
    let kind = expected.scalar_type.token();
    let prefix = anydata_query_prefix();
    let sql = format!("DECLARE l_anydata SYS.ANYDATA; l_type_name VARCHAR2(4000); l_match_count PLS_INTEGER; {extra} BEGIN {construction} IF l_anydata IS NULL THEN RAISE_APPLICATION_ERROR(-20001, 'native_job_argument_conversion_loss'); END IF; l_type_name := l_anydata.GetTypeName(); {prefix}SELECT COUNT(*) INTO l_match_count FROM DBX_ANYDATA_UNIQUE WHERE CODEC = '{kind}' AND SYS.UTL_RAW.CAST_TO_RAW(TYPE_NAME) = SYS.UTL_RAW.CAST_TO_RAW(l_type_name); IF l_match_count <> 1 THEN RAISE_APPLICATION_ERROR(-20001, 'native_job_argument_type_unverified'); END IF; {validation}{} END;", setter.unwrap_or(""));
    Ok((sql, expected))
}

/// Parse an explicit envelope only. JSON-looking strings retain their original string contract.
pub fn number_envelope(value: &Value) -> Result<ArgumentExpectation, &'static str> {
    let object = value.as_object().ok_or("native_job_argument_value_invalid")?;
    if object.len() != 3
        || object.get("$dbx").and_then(Value::as_str) != Some("oracle-anydata-v1")
        || object.get("typeName").and_then(Value::as_str) != Some("SYS.NUMBER")
    {
        return Err("native_job_argument_value_invalid");
    }
    let value = object.get("value").and_then(Value::as_str).ok_or("native_job_argument_value_invalid")?;
    Ok(ArgumentExpectation { scalar_type: ScalarType::Number, value: Some(Value::String(normalize_number(value)?)) })
}

pub fn number_anydata_expression(value: &Value) -> Result<(String, NativeJobArgumentValue), &'static str> {
    let scalar = number_envelope(value)?;
    let Some(Value::String(number)) = &scalar.value else { unreachable!() };
    Ok((format!("SYS.ANYDATA.ConvertNumber({number})"), scalar.editable_value()))
}

pub fn null_anydata_expression(data_type: &str) -> Result<(String, ArgumentExpectation), &'static str> {
    let kind = match data_type.to_ascii_uppercase().as_str() {
        "VARCHAR2" | "VARCHAR" | "CHAR" => ScalarType::Varchar2,
        "NUMBER" | "INTEGER" => ScalarType::Number,
        "DATE" => ScalarType::Date,
        "TIMESTAMP" => ScalarType::Timestamp,
        "TIMESTAMP WITH TIME ZONE" => ScalarType::TimestampTz,
        "TIMESTAMP WITH LOCAL TIME ZONE" => ScalarType::TimestampLtz,
        "NVARCHAR2" => ScalarType::Nvarchar2,
        "NCHAR" => ScalarType::Nchar,
        "INTERVAL YEAR TO MONTH" => ScalarType::IntervalYm,
        "INTERVAL DAY TO SECOND" => ScalarType::IntervalDs,
        "RAW" => ScalarType::Raw,
        "BINARY_FLOAT" => ScalarType::BinaryFloat,
        "BINARY_DOUBLE" => ScalarType::BinaryDouble,
        "UROWID" => ScalarType::Urowid,
        _ => return Err("native_job_argument_type_required_for_null"),
    };
    Ok((kind.null_expression(), ArgumentExpectation { scalar_type: kind, value: None }))
}

pub fn oracle_argument_matches(row: &NativeJobRow, desired: &NativeJobArgumentValue, data_type: &str) -> bool {
    let expected = match desired {
        NativeJobArgumentValue::Null => null_anydata_expression(data_type).map(|(_, storage)| storage),
        NativeJobArgumentValue::Value { value: Value::String(text) } if text.is_empty() => {
            null_anydata_expression(data_type).map(|(_, storage)| storage)
        }
        NativeJobArgumentValue::Value { value: Value::String(text) } => {
            return decode_argument(row, false) == ArgumentStorage::Text(text.clone())
        }
        NativeJobArgumentValue::Value { value } => scalar_envelope(value),
        _ => return false,
    };
    expected.is_ok_and(|expected| expected.matches(&decode_argument(row, false)))
}

pub fn canonical_argument_row(row: &NativeJobRow, default_value: bool) -> NativeJobRow {
    let storage = decode_argument(row, default_value);
    if matches!(storage, ArgumentStorage::Opaque(_)) {
        return row.clone();
    }
    let mut canonical = row.clone();
    canonical.retain(|key, _| {
        !matches!(
            key.as_str(),
            "DBX_ANYDATA_PRESENT"
                | "DBX_ANYDATA_TYPE"
                | "DBX_ANYDATA_IS_NULL"
                | "DBX_ANYDATA_TEXT"
                | "DBX_ANYDATA_CODEC"
                | "DBX_ANYDATA_CONSTRUCTOR_TYPE"
                | "DBX_ANYDATA_DAY"
                | "DBX_ANYDATA_SECONDS"
                | "DBX_ANYDATA_TZ_REGION"
                | "DBX_ANYDATA_TZ_OFFSET"
                | "DBX_ANYDATA_TZ_ABBR"
                | "DBX_ANYDATA_HEX"
                | "DBX_ANYDATA_LENGTH"
                | "DBX_ARGUMENT_DEFAULT"
                | "DBX_ANYDATA_CIVIL_DATE"
        ) && if default_value {
            !matches!(key.as_str(), "DEFAULT_VALUE" | "DEFAULT_ANYDATA_VALUE")
        } else {
            !matches!(key.as_str(), "VALUE" | "ANYDATA_VALUE")
        }
    });
    canonical.insert("DBX_ARGUMENT_CANONICAL".into(), storage.canonical_value());
    canonical
}

pub fn validate_lightweight_argument(style: Option<&str>, value: &NativeJobArgumentValue) -> Result<(), &'static str> {
    let string_setter_or_reset = match value {
        NativeJobArgumentValue::Unset | NativeJobArgumentValue::Inherit => true,
        NativeJobArgumentValue::Value { value: Value::String(text) } => !text.is_empty(),
        _ => false,
    };
    if style.is_some_and(|style| style.eq_ignore_ascii_case("LIGHTWEIGHT")) && !string_setter_or_reset {
        return Err("native_job_lightweight_anydata_unsupported");
    }
    Ok(())
}

/// Storage identity is part of equality: a VARCHAR override and ANYDATA VARCHAR2 are not interchangeable.
#[derive(Clone, PartialEq)]
pub enum ArgumentStorage {
    Text(String),
    TypedNull { type_name: String, scalar_type: ScalarType },
    Scalar { type_name: String, scalar_type: ScalarType, value: Value },
    Opaque(NativeJobRow),
}

impl ArgumentStorage {
    pub fn editable_value(&self) -> NativeJobArgumentValue {
        match self {
            Self::Text(value) => NativeJobArgumentValue::Value { value: Value::String(value.clone()) },
            Self::TypedNull { scalar_type, .. } => {
                ArgumentExpectation { scalar_type: *scalar_type, value: None }.editable_value()
            }
            Self::Scalar { scalar_type, value, .. } => {
                ArgumentExpectation { scalar_type: *scalar_type, value: Some(value.clone()) }.editable_value()
            }
            Self::Opaque(row) => NativeJobArgumentValue::Opaque { value: json!(row) },
        }
    }

    /// Excludes driver-specific locator text only after a complete value has been decoded.
    pub fn canonical_value(&self) -> Value {
        match self {
            Self::Text(value) => json!({"storage": "varchar", "value": value}),
            Self::TypedNull { type_name, scalar_type } => {
                json!({"storage": "anydata", "typeName": type_name, "scalarType": scalar_type.token(), "isNull": true})
            }
            Self::Scalar { type_name, scalar_type, value } => {
                json!({"storage": "anydata", "typeName": type_name, "scalarType": scalar_type.token(), "isNull": false, "value": value})
            }
            Self::Opaque(row) => json!({"storage": "opaque", "row": row}),
        }
    }
}

#[derive(Clone)]
pub struct ArgumentExpectation {
    pub scalar_type: ScalarType,
    pub value: Option<Value>,
}

impl ArgumentExpectation {
    pub fn editable_value(&self) -> NativeJobArgumentValue {
        match &self.value {
            None => NativeJobArgumentValue::Value {
                value: json!({"$dbx":"oracle-anydata-v1", "scalarType":self.scalar_type.token(), "value":null}),
            },
            Some(value) => NativeJobArgumentValue::Value {
                value: if self.scalar_type == ScalarType::Number {
                    json!({"$dbx":"oracle-anydata-v1", "typeName":"SYS.NUMBER", "value":value})
                } else {
                    json!({"$dbx":"oracle-anydata-v1", "scalarType":self.scalar_type.token(), "value":value})
                },
            },
        }
    }

    pub fn matches(&self, actual: &ArgumentStorage) -> bool {
        match (actual, &self.value) {
            (ArgumentStorage::TypedNull { scalar_type, .. }, None) => *scalar_type == self.scalar_type,
            (ArgumentStorage::Scalar { scalar_type, value, .. }, Some(expected)) => {
                *scalar_type == self.scalar_type && value == expected
            }
            _ => false,
        }
    }
}

fn projected_boolean(value: Option<&Value>) -> Option<bool> {
    match value? {
        Value::Bool(value) => Some(*value),
        Value::Number(value) if value.as_u64() == Some(0) => Some(false),
        Value::Number(value) if value.as_u64() == Some(1) => Some(true),
        Value::String(value) if value == "0" || value.eq_ignore_ascii_case("false") => Some(false),
        Value::String(value) if value == "1" || value.eq_ignore_ascii_case("true") => Some(true),
        _ => None,
    }
}

/// Decode only proven native values. Presence never falls back to a misleading VALUE column.
/// `default_value` selects the Program-default column; projected evidence uses the same aliases.
pub fn decode_argument(row: &NativeJobRow, default_value: bool) -> ArgumentStorage {
    let opaque = || ArgumentStorage::Opaque(row.clone());
    if row.get("OUT_ARGUMENT").is_some_and(|value| projected_boolean(Some(value)) != Some(false)) {
        return opaque();
    }
    match projected_boolean(row.get("DBX_ANYDATA_PRESENT")) {
        Some(false) => {
            let column = if default_value { "DEFAULT_VALUE" } else { "VALUE" };
            row.get(column)
                .and_then(Value::as_str)
                .map(|value| ArgumentStorage::Text(value.into()))
                .unwrap_or_else(opaque)
        }
        Some(true) => {
            let Some(type_name) = row.get("DBX_ANYDATA_TYPE").and_then(Value::as_str) else { return opaque() };
            let Some(scalar_type) = identity::proven_type(row, type_name) else {
                return opaque();
            };
            match projected_boolean(row.get("DBX_ANYDATA_IS_NULL")) {
                Some(true) => ArgumentStorage::TypedNull { type_name: type_name.into(), scalar_type },
                Some(false) => {
                    let Ok(value) = scalars::projected_value(scalar_type, row) else {
                        return opaque();
                    };
                    ArgumentStorage::Scalar { type_name: type_name.into(), scalar_type, value }
                }
                None => opaque(),
            }
        }
        None => opaque(),
    }
}

/// Canonicalize an exactly representable Oracle NUMBER without floating-point conversion.
pub fn normalize_number(value: &str) -> Result<String, &'static str> {
    const INVALID: &str = "native_job_argument_value_invalid";
    let mut parts = value.split(['e', 'E']);
    let mantissa = parts.next().ok_or(INVALID)?;
    let exponent = match parts.next() {
        Some(value) => value.parse::<i64>().map_err(|_| INVALID)?,
        None => 0,
    };
    if parts.next().is_some() {
        return Err(INVALID);
    }
    let negative = mantissa.starts_with('-');
    let unsigned = mantissa.strip_prefix(['+', '-']).unwrap_or(mantissa);
    let mut decimal_seen = false;
    let mut fractional_digits = 0_i64;
    let mut digits = String::with_capacity(unsigned.len());
    for byte in unsigned.bytes() {
        match byte {
            b'.' if !decimal_seen => decimal_seen = true,
            b'0'..=b'9' => {
                digits.push(char::from(byte));
                if decimal_seen {
                    fractional_digits = fractional_digits.checked_add(1).ok_or(INVALID)?;
                }
            }
            _ => return Err(INVALID),
        }
    }
    if digits.is_empty() {
        return Err(INVALID);
    }
    let significant = digits.trim_start_matches('0');
    if significant.is_empty() {
        return Ok("0".into());
    }
    let coefficient = significant.trim_end_matches('0');
    let trailing_zeros = i64::try_from(significant.len() - coefficient.len()).map_err(|_| INVALID)?;
    let low = exponent.checked_sub(fractional_digits).and_then(|n| n.checked_add(trailing_zeros)).ok_or(INVALID)?;
    let high = low.checked_add(i64::try_from(coefficient.len() - 1).map_err(|_| INVALID)?).ok_or(INVALID)?;
    // Each base-100 digit spans powers 2n and 2n+1, also for negative powers.
    // Removing decimal trailing zeroes does not remove a partial base-100 digit.
    if !(-130..=125).contains(&high) || high.div_euclid(2) - low.div_euclid(2) + 1 > 20 {
        return Err(INVALID);
    }
    let sign = if negative { "-" } else { "" };
    let fraction = if coefficient.len() > 1 { format!(".{}", &coefficient[1..]) } else { String::new() };
    Ok(format!("{sign}{}{fraction}E{high}", &coefficient[..1]))
}

