    #[test]
    fn anydata_presence_and_native_null_require_complete_evidence() {
        let row = number_row(json!("9007199254740993"));
        assert!(matches!(decode_argument(&row, false), ArgumentStorage::Scalar { .. }));
        for key in ["DBX_ANYDATA_PRESENT", "DBX_ANYDATA_TYPE", "DBX_ANYDATA_IS_NULL", "DBX_ANYDATA_TEXT"] {
            let mut incomplete = row.clone();
            incomplete.remove(key);
            assert!(matches!(decode_argument(&incomplete, false), ArgumentStorage::Opaque(_)), "{key}");
        }
        let mut unknown = row.clone();
        unknown.insert("DBX_ANYDATA_TYPE".into(), json!("APP.OBJECT"));
        assert!(matches!(decode_argument(&unknown, false), ArgumentStorage::Opaque(_)));
        let mut typed_null = row;
        typed_null.insert("DBX_ANYDATA_IS_NULL".into(), json!(1));
        let number_null = decode_argument(&typed_null, false);
        typed_null.insert("DBX_ANYDATA_TYPE".into(), json!("SYS.DATE"));
        assert!(number_null != decode_argument(&typed_null, false));
        assert!(
            matches!(number_null.editable_value(), NativeJobArgumentValue::Value { value } if value == json!({"$dbx":"oracle-anydata-v1","scalarType":"number","value":null}))
        );
    }

